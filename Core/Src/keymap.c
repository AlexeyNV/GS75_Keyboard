KeyId Keymap_At(uint32_t row, uint32_t col)
{
    return row < MATRIX_ROWS && col < MATRIX_COLS ? keymap[row][col] : KEY_NONE;
}

const char *Keymap_Name(KeyId key)
{
    return (uint32_t)key < KEY_ID_COUNT ? key_names[key] : "KEY_NONE";
}

const char *Keymap_Label(KeyId key)
{
    return (uint32_t)key < KEY_ID_COUNT ? key_labels[key] : "";
}
